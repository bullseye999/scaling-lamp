"""
ciph/kernel/candidate_construction - 4.6 Gate Two: can the change become an isolated artifact?

Generation has creativity but no standing. This module writes bytes INTO A STAGING BOUNDARY and then
hands them to the 4.5 registry, which is the only thing that can say a candidate exists.

LAWS
 1. Construction cannot modify the active implementation.
 2. Construction cannot modify the baseline artifact.
 3. Construction cannot write the active-candidate pointer.
 4. Construction cannot issue execution authority.
 5. Generated bytes are untrusted until registered.
 6. Registration freezes candidate identity.
 7. Bytes changed after registration -> identity mismatch or a new candidate.
 8. Generator identity and version are recorded.
 9. Construction failure is evidence about the GENERATOR, not about the hypothesis.
10. Restart never turns a partial candidate into an accepted candidate.
11. Staging artifacts cannot become production merely by existing.
12. Same frozen artifact/configuration -> same Crucible candidate identity.
"""

import json
import os
import pathlib
import sqlite3
import time
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Sequence, Tuple

from ciph.kernel.crucible_candidates import CrucibleCandidate, register_candidate
from ciph.kernel.crucible_types import CrucibleError, digest, KIND_CAPABILITY_IMPLEMENTATION
from ciph.kernel.improvement_hypotheses import get_hypothesis

CANDIDATE_CONSTRUCTION_V1 = "CANDIDATE_CONSTRUCTION_V1"

_SCHEMA = (
    """
    CREATE TABLE IF NOT EXISTS ciph_candidate_constructions (
        construction_id TEXT PRIMARY KEY,
        hypothesis_id TEXT NOT NULL,
        baseline_candidate_id TEXT,
        staging_ref TEXT NOT NULL,
        artifact_digest TEXT,
        configuration_digest TEXT,
        generator_identity TEXT NOT NULL,
        generator_version TEXT,
        construction_inputs_digest TEXT NOT NULL,
        crucible_candidate_id TEXT,
        status TEXT NOT NULL,
        reason TEXT,
        created_at REAL
    );
    """,
)


class StagingSandbox:
    """
    The only filesystem a candidate generator may write to.

    Containment is computed on the RESOLVED path, so `..`, symlinks and absolute paths cannot walk out
    of the boundary. This is a mechanism, deliberately narrow: it does not decide what a candidate is,
    and it cannot reach a live file because it refuses the path first.
    """

    def __init__(self, root: Any):
        self.root = pathlib.Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def resolve(self, name: str) -> pathlib.Path:
        candidate = (self.root / str(name)).resolve()
        if candidate != self.root and self.root not in candidate.parents:
            raise CrucibleError("STAGING_ESCAPE_REFUSED", str(name))
        return candidate

    def write(self, name: str, data: bytes) -> pathlib.Path:
        """Write atomically: a partial artifact is never visible under its final name (law 10)."""
        target = self.resolve(name)
        partial = target.with_name(target.name + '.partial')
        partial.write_bytes(data)
        os.replace(partial, target)
        return target

    def read(self, name: str) -> bytes:
        return self.resolve(name).read_bytes()


def _connect(db_path: str, *, read_only: bool = False) -> sqlite3.Connection:
    if read_only:
        try:
            connection = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True, timeout=10.0)
            connection.row_factory = sqlite3.Row
            return connection
        except sqlite3.OperationalError:
            pass
    connection = sqlite3.connect(db_path, timeout=10.0)
    connection.row_factory = sqlite3.Row
    return connection


def init_schema(conn: sqlite3.Connection) -> None:
    for statement in _SCHEMA:
        conn.execute(statement)


@dataclass(frozen=True)
class CandidateConstructionRecord:
    construction_id: str
    hypothesis_id: str
    baseline_candidate_id: Optional[str]
    staging_ref: str
    artifact_digest: Optional[str]
    configuration_digest: Optional[str]
    generator_identity: str
    generator_version: Optional[str]
    construction_inputs_digest: str
    crucible_candidate_id: Optional[str]
    status: str
    reason: Optional[str]

    def as_dict(self) -> Dict[str, Any]:
        return {"construction_id": self.construction_id, "hypothesis_id": self.hypothesis_id,
                "baseline_candidate_id": self.baseline_candidate_id,
                "staging_ref": self.staging_ref, "artifact_digest": self.artifact_digest,
                "configuration_digest": self.configuration_digest,
                "generator_identity": self.generator_identity,
                "generator_version": self.generator_version,
                "construction_inputs_digest": self.construction_inputs_digest,
                "crucible_candidate_id": self.crucible_candidate_id, "status": self.status,
                "reason": self.reason}


def construct_candidate(db_path: str, *, hypothesis_id: str, sandbox: StagingSandbox,
                        artifact_name: str, artifact_bytes: bytes,
                        generator_identity: str, generator_version: Optional[str] = None,
                        generator_strategy_id: Optional[str] = None,
                        manifest_identity: Optional[str] = None,
                        now: Optional[float] = None) -> CandidateConstructionRecord:
    """
    Write ONE artifact into staging and hand it to the registry.

    The returned `crucible_candidate_id` is a `CC-*` identity allocated by 4.5. This module never mints
    an identity of its own, so there is exactly one answer to "which candidate is this?".
    """
    hypothesis = get_hypothesis(db_path, hypothesis_id)
    moment = time.time() if now is None else float(now)
    # The artifact digest is part of the construction identity. Without it, editing the bytes and
    # rebuilding under the same name would collide on the construction id and return the OLD record -
    # a stale identity wearing the new artifact's clothes.
    artifact_digest = digest(artifact_bytes)
    inputs_digest = digest({"hypothesis": hypothesis.basis_digest,
                            "artifact_name": str(artifact_name),
                            "artifact": artifact_digest,
                            "strategy": generator_strategy_id,
                            "generator": generator_identity})
    construction_id = "CON-" + inputs_digest[:16].upper()

    try:
        path = sandbox.write(str(artifact_name), artifact_bytes)
    except CrucibleError as refused:
        return _record(db_path, construction_id, hypothesis, sandbox.root, None, None,
                       generator_identity, generator_version, inputs_digest, None, 'FAILED',
                       refused.reason, moment)
    except OSError as error:
        return _record(db_path, construction_id, hypothesis, sandbox.root, None, None,
                       generator_identity, generator_version, inputs_digest, None, 'FAILED',
                       f'IO:{error.__class__.__name__}', moment)

    configuration_digest = digest({"generator": generator_identity,
                                   "version": generator_version,
                                   "strategy": generator_strategy_id,
                                   "hypothesis": hypothesis.basis_digest})
    candidate = register_candidate(
        db_path, kind=KIND_CAPABILITY_IMPLEMENTATION, artifact_digest=artifact_digest,
        configuration_digest=configuration_digest, manifest_identity=manifest_identity,
        baseline_candidate_id=hypothesis.baseline_candidate_id,
        declared_objective=f'hypothesis:{hypothesis_id}',
        created_by=generator_identity, now=moment)
    return _record(db_path, construction_id, hypothesis, path, artifact_digest,
                   configuration_digest, generator_identity, generator_version, inputs_digest,
                   candidate.candidate_id, 'REGISTERED', None, moment)


def _record(db_path: str, construction_id: str, hypothesis: Any, staging_ref: Any,
            artifact_digest: Optional[str], configuration_digest: Optional[str],
            generator_identity: str, generator_version: Optional[str], inputs_digest: str,
            candidate_id: Optional[str], status: str, reason: Optional[str],
            moment: float) -> CandidateConstructionRecord:
    connection = _connect(db_path)
    try:
        init_schema(connection)
        connection.execute(
            "INSERT OR IGNORE INTO ciph_candidate_constructions (construction_id, hypothesis_id, "
            "baseline_candidate_id, staging_ref, artifact_digest, configuration_digest, "
            "generator_identity, generator_version, construction_inputs_digest, "
            "crucible_candidate_id, status, reason, created_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?);",
            (construction_id, hypothesis.hypothesis_id, hypothesis.baseline_candidate_id,
             str(staging_ref), artifact_digest, configuration_digest, generator_identity,
             generator_version, inputs_digest, candidate_id, status, reason, moment))
        connection.commit()
    finally:
        connection.close()
    return get_construction(db_path, construction_id)


def get_construction(db_path: str, construction_id: str) -> CandidateConstructionRecord:
    connection = _connect(db_path, read_only=True)
    try:
        row = connection.execute("SELECT * FROM ciph_candidate_constructions WHERE "
                                 "construction_id = ?;", (construction_id,)).fetchone()
    except sqlite3.Error:
        row = None
    finally:
        connection.close()
    if row is None:
        raise CrucibleError("UNKNOWN_CONSTRUCTION", construction_id)
    row = dict(row)
    return CandidateConstructionRecord(
        construction_id=str(row["construction_id"]), hypothesis_id=str(row["hypothesis_id"]),
        baseline_candidate_id=row["baseline_candidate_id"], staging_ref=str(row["staging_ref"]),
        artifact_digest=row["artifact_digest"], configuration_digest=row["configuration_digest"],
        generator_identity=str(row["generator_identity"]), generator_version=row["generator_version"],
        construction_inputs_digest=str(row["construction_inputs_digest"]),
        crucible_candidate_id=row["crucible_candidate_id"], status=str(row["status"]),
        reason=row["reason"])


def construction_history(db_path: str, hypothesis_id: Optional[str] = None
                         ) -> List[CandidateConstructionRecord]:
    connection = _connect(db_path, read_only=True)
    query = "SELECT construction_id FROM ciph_candidate_constructions"
    params: Tuple[Any, ...] = ()
    if hypothesis_id is not None:
        query += " WHERE hypothesis_id = ?"
        params = (hypothesis_id,)
    try:
        ids = [str(row["construction_id"]) for row in connection.execute(
            query + " ORDER BY created_at, construction_id;", params)]
    except sqlite3.Error:
        ids = []
    finally:
        connection.close()
    return [get_construction(db_path, construction_id) for construction_id in ids]


def construction_digest(db_path: str) -> str:
    return digest({"version": CANDIDATE_CONSTRUCTION_V1,
                   "constructions": [item.as_dict() for item in construction_history(db_path)]})
